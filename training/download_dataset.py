import argparse
import sys
import shutil
from pathlib import Path

# Project root
PROJECT_ROOT = Path(__file__).parent.parent
DATASET_DIR = PROJECT_ROOT / "datasets"


def download_from_roboflow(api_key: str, workspace: str, project: str, version: int):
    """Download a dataset from Roboflow."""
    try:
        from roboflow import Roboflow
    except ImportError:
        print("❌ Roboflow not installed. Run: pip install roboflow")
        sys.exit(1)

    print(f"\n📥 Downloading: {workspace}/{project} v{version}")
    print("=" * 50)

    rf = Roboflow(api_key=api_key)
    project_obj = rf.workspace(workspace).project(project)
    version_obj = project_obj.version(version)

    # Download in YOLOv8 format
    dataset = version_obj.download(
        model_format="yolov8",
        location=str(DATASET_DIR / "raw" / f"{project}-v{version}"),
        overwrite=True,
    )

    return dataset.location


def merge_datasets(raw_dirs: list, output_dir: Path):
    """Merge multiple downloaded datasets into one unified dataset."""
    print("\n🔄 Merging datasets...")
    print("=" * 50)

    splits = ["train", "valid", "test"]

    for split in splits:
        img_dir = output_dir / split / "images"
        lbl_dir = output_dir / split / "labels"
        img_dir.mkdir(parents=True, exist_ok=True)
        lbl_dir.mkdir(parents=True, exist_ok=True)

    total_images = 0
    for raw_dir in raw_dirs:
        raw_path = Path(raw_dir)
        if not raw_path.exists():
            print(f"  ⚠️  Skipping {raw_dir} (not found)")
            continue

        for split in splits:
            src_img = raw_path / split / "images"
            src_lbl = raw_path / split / "labels"

            if not src_img.exists():
                continue

            count = 0
            for img_file in src_img.iterdir():
                if img_file.suffix.lower() in [".jpg", ".jpeg", ".png", ".bmp"]:
                    # Copy image
                    dest_img = output_dir / split / "images" / img_file.name
                    if not dest_img.exists():
                        shutil.copy2(img_file, dest_img)
                        count += 1

                        # Copy corresponding label
                        lbl_file = src_lbl / (img_file.stem + ".txt")
                        if lbl_file.exists():
                            dest_lbl = output_dir / split / "labels" / lbl_file.name
                            shutil.copy2(lbl_file, dest_lbl)

            total_images += count
            print(f"  ✅ {split}: +{count} images from {raw_path.name}")

    print(f"\n📊 Total images merged: {total_images}")
    return total_images


def update_data_yaml(output_dir: Path):
    """Update data.yaml with correct paths."""
    data_yaml = output_dir / "data.yaml"
    content = f"""# Pothole Detection Dataset (Merged)
# Auto-generated by download_dataset.py

path: {output_dir.resolve().as_posix()}
train: train/images
val: valid/images
test: test/images

nc: 1
names:
  0: pothole
"""
    data_yaml.write_text(content, encoding="utf-8")
    print(f"  📝 Updated {data_yaml}")


def count_dataset(output_dir: Path):
    """Count and display dataset statistics."""
    print("\n📊 Dataset Statistics")
    print("=" * 50)

    total = 0
    for split in ["train", "valid", "test"]:
        img_dir = output_dir / split / "images"
        if img_dir.exists():
            count = len(list(img_dir.glob("*")))
            total += count
            print(f"  {split:>8}: {count:>6} images")
        else:
            print(f"  {split:>8}:      0 images")

    print(f"  {'TOTAL':>8}: {total:>6} images")
    print()

    if total < 10000:
        print(f"  ⚠️  Dataset has {total} images. Target is 10,000+")
        print("  💡 Tips to increase dataset size:")
        print("     - Add more Roboflow datasets (edit DATASETS list)")
        print("     - Use data augmentation during training")
        print("     - Collect and annotate your own images")
    else:
        print(f"  ✅ Dataset target reached! ({total} >= 10,000)")

    return total


