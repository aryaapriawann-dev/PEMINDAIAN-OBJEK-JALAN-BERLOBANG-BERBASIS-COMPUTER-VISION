def main():
    parser = argparse.ArgumentParser(
        description="Download pothole detection datasets from Roboflow"
    )
    parser.add_argument(
        "--api_key",
        type=str,
        required=True,
        help="Roboflow API key (get free at https://app.roboflow.com)"
    )
    parser.add_argument(
        "--skip_download",
        action="store_true",
        help="Skip download and only merge existing raw datasets"
    )
    args = parser.parse_args()

    print("🚧 Pothole Detection - Dataset Downloader")
    print("=" * 50)
    print(f"📂 Output directory: {DATASET_DIR}")
    print(f"📦 Datasets to download: {len(DATASETS)}")

    raw_dirs = []

    if not args.skip_download:
        for ds in DATASETS:
            print(f"\n📋 {ds['description']}")
            try:
                location = download_from_roboflow(
                    api_key=args.api_key,
                    workspace=ds["workspace"],
                    project=ds["project"],
                    version=ds["version"]
                )
                raw_dirs.append(location)
            except Exception as e:
                print(f"  ❌ Error downloading: {e}")
                # Try to use existing raw data
                fallback = DATASET_DIR / "raw" / f"{ds['project']}-v{ds['version']}"
                if fallback.exists():
                    print(f"  🔄 Using existing data: {fallback}")
                    raw_dirs.append(str(fallback))
    else:
        # Use existing raw directories
        raw_root = DATASET_DIR / "raw"
        if raw_root.exists():
            raw_dirs = [str(p) for p in raw_root.iterdir() if p.is_dir()]
        print(f"  📂 Found {len(raw_dirs)} existing raw datasets")

    if raw_dirs:
        # Merge all datasets
        merge_datasets(raw_dirs, DATASET_DIR)
        update_data_yaml(DATASET_DIR)

    # Count final dataset
    count_dataset(DATASET_DIR)

    print("\n✅ Done! Next step: Train the model")
    print("   python training/train.py")


if __name__ == "__main__":
    main()
